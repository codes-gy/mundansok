CREATE TABLE domain (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name               VARCHAR(253) NOT NULL UNIQUE,
    verification_token VARCHAR(64)  NOT NULL,
    verified_at        TIMESTAMP WITH TIME ZONE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE scan (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    domain_id   BIGINT      NOT NULL REFERENCES domain (id),
    status      VARCHAR(16) NOT NULL,
    score       INT,
    error       VARCHAR(500),
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL,
    finished_at TIMESTAMP WITH TIME ZONE
);

-- 10분 제한 확인용: 도메인별 최근 점검
CREATE INDEX idx_scan_domain_created ON scan (domain_id, created_at DESC);

CREATE TABLE finding (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scan_id        BIGINT       NOT NULL REFERENCES scan (id),
    check_id       VARCHAR(32)  NOT NULL,
    severity       VARCHAR(8)   NOT NULL,
    title          VARCHAR(200) NOT NULL,
    detail         VARCHAR(500) NOT NULL,
    recommendation VARCHAR(500) NOT NULL
);

CREATE INDEX idx_finding_scan ON finding (scan_id);
