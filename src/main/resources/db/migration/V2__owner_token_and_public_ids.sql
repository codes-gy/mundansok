-- 소유 인증을 "등록한 사람"에게 묶는다.
-- 이전에는 도메인 행 하나에 인증 토큰 · 인증 상태가 있어서, 같은 도메인을 다시 등록한 누구에게나 기존 토큰과 인증 상태가 넘어갔다.
-- 이제 등록마다 domain_claim 한 행 + 소유자 토큰(해시만 저장)을 만들고, 인증 · 점검 · 결과 조회에 토큰을 요구한다.
-- 이전 등록에는 소유자 토큰이 없으므로 옮기지 않는다 (다시 등록 · 인증해야 한다).
CREATE TABLE domain_claim (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id          UUID         NOT NULL UNIQUE,
    domain_id          BIGINT       NOT NULL REFERENCES domain (id),
    owner_secret_hash  VARCHAR(64)  NOT NULL,
    verification_token VARCHAR(64)  NOT NULL,
    verified_at        TIMESTAMP WITH TIME ZONE,
    created_at         TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE INDEX idx_domain_claim_domain ON domain_claim (domain_id);

-- 쿨다운: 조건부 UPDATE 한 문장으로 확인 + 기록해 동시 요청에도 하나만 통과시킨다
ALTER TABLE domain ADD COLUMN last_scan_requested_at TIMESTAMP WITH TIME ZONE;
UPDATE domain SET last_scan_requested_at = (SELECT MAX(s.created_at) FROM scan s WHERE s.domain_id = domain.id);

ALTER TABLE domain DROP COLUMN verification_token;
ALTER TABLE domain DROP COLUMN verified_at;

-- 점검 결과는 추측할 수 없는 UUID로 내보내고, 요청한 등록에 묶는다.
-- 이전 기록은 public_id · claim_id가 null로 남아 API로 조회할 수 없다
ALTER TABLE scan ADD COLUMN public_id UUID;
ALTER TABLE scan ADD COLUMN claim_id BIGINT;
ALTER TABLE scan ADD CONSTRAINT uk_scan_public_id UNIQUE (public_id);
ALTER TABLE scan ADD CONSTRAINT fk_scan_claim FOREIGN KEY (claim_id) REFERENCES domain_claim (id);
